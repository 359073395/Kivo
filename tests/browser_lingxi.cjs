const { chromium } = require('../.venv/Lib/site-packages/playwright/driver/package');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const target = process.env.LINGXI_QA_URL || 'http://127.0.0.1:7861/';
  const evidence = process.env.LINGXI_QA_OUTPUT || 'F:/820/lingxi-platform/qa/evidence';
  fs.mkdirSync(evidence, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: "C:/Users/w'k'r/AppData/Local/ms-playwright/chromium_headless_shell-1228/chrome-headless-shell-win64/chrome-headless-shell.exe" });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/*', (route) => {
    const url = new URL(route.request().url());
    return url.hostname === '127.0.0.1' ? route.continue() : route.abort();
  });
  const page = await context.newPage();
  const failures = [];
  const checks = [];
  page.on('pageerror', (error) => failures.push(error.message));
  const check = (name, condition) => { if (!condition) throw new Error(name); checks.push(name); };
  try {
    await page.goto(target, { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: '先用通用模式', exact: true }).waitFor({ timeout: 15000 }).catch(() => {});
    if (await page.getByRole('button', { name: '先用通用模式', exact: true }).isVisible().catch(() => false))
      await page.getByRole('button', { name: '先用通用模式', exact: true }).click();
    // Initial model setup may appear on a clean QA service. Knowledge work remains available.
    const close = page.locator('.settings-overlay .settings-close');
    await close.waitFor({ state: 'visible', timeout: 20000 }).catch(() => {});
    if (await close.isVisible().catch(() => false)) await close.click();
    await page.getByRole('button', { name: '学习知识库', exact: true }).click();
    await page.getByRole('heading', { name: '让每次创作，都有知识可依' }).waitFor();
    check('domestic_brand', (await page.title()) === 'Kivo 创作工作台');
    await page.getByLabel('搜索知识', { exact: true }).fill('人群定位');
    await page.locator('.lx-k-result').first().waitFor();
    await page.locator('.lx-k-result').first().click();
    check('knowledge_source_visible', await page.getByText('查看来源与版本', { exact: true }).isVisible());
    await page.screenshot({ path: path.join(evidence, 'knowledge-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: '辅助创作与校验', exact: true }).click();
    await page.getByLabel('待检查标题', { exact: true }).fill('100%有效');
    await page.getByLabel('待检查正文', { exact: true }).fill('人人适用，保证有效。');
    await page.getByRole('button', { name: '检查文本', exact: true }).click();
    await page.getByText(/请核对依据或改写这些承诺/).waitFor();
    check('visible_claim_check', await page.getByText(/未提供本账号\/产品事实/).isVisible());
    await page.getByRole('button', { name: '学习新资料', exact: true }).click();
    await page.getByLabel('资料标题', { exact: true }).fill('QA独立学习资料');
    await page.getByLabel('来源说明', { exact: true }).fill('合成UI验收，不作为营销事实');
    await page.getByLabel('完整文字稿', { exact: true }).fill('本资料用于页面验收。内容面向社区咖啡店老板，先确认真实经历和产品事实，再创作标题与正文；缺少证据时保留待核，不能编造粉丝和成交成绩。');
    await page.getByRole('button', { name: '保存并进入学习', exact: true }).click();
    await page.getByText('资料已保存，当前为待审核；请核对候选方法。', { exact: true }).waitFor();
    check('learning_candidate_saved', await page.getByRole('heading', { name: 'QA独立学习资料', exact: true }).isVisible());
    await page.getByLabel('审核后的方法', { exact: true }).fill('适用：社区咖啡店内容。输入：真实经历与产品事实。步骤：核对事实后设计场景标题。检查：标题能兑现。停止：出现无依据成绩。反馈：关联同版内容的实际数据。');
    await page.getByRole('button', { name: '确认方法并用于后续创作', exact: true }).click();
    await page.getByText('方法已加入国内版创作知识；原始知识库规则未自动改写。', { exact: true }).waitFor();
    check('learning_approved', true);
    await page.screenshot({ path: path.join(evidence, 'learning-desktop.png'), fullPage: true });
    await page.getByLabel('资料标题', { exact: true }).fill('QA手动直接使用方法');
    await page.getByLabel('完整文字稿', { exact: true }).fill('适用当前国内版创作；先核事实再设计场景标题，检查正文能兑现承诺，缺少证据时停止编造，后续按同口径数据复盘。');
    await page.getByRole('checkbox', { name: '这是我已确认的方法，保存后直接用于后续创作' }).check();
    await page.getByRole('button', { name: '保存并直接使用', exact: true }).click();
    await page.getByText('方法已保存，可直接用于后续创作。', { exact: true }).waitFor();
    check('manual_knowledge_direct_use', true);
    await page.getByRole('button', { name: '数据反馈与自学习', exact: true }).click();
    await page.getByLabel('反馈账号', { exact: true }).fill('QA学习账号');
    await page.getByLabel('内容编号', { exact: true }).fill('qa-feedback-001');
    await page.getByLabel('反馈作品标题', { exact: true }).fill('本地合成反馈验收');
    await page.getByLabel('数据来源', { exact: true }).fill('合成测试，不代表实际运营成绩');
    await page.getByLabel('观察时长（小时）', { exact: true }).fill('24');
    await page.getByLabel('反馈播放 / 阅读', { exact: true }).fill('1000');
    await page.getByLabel('反馈点赞', { exact: true }).fill('50');
    await page.getByRole('button', { name: '保存反馈并自动学习', exact: true }).click();
    await page.getByText('反馈已自动学习；本账号后续创作可参考，未修改全局规则。', { exact: true }).waitFor();
    check('feedback_automatic_learning', true);
    await page.getByRole('button', { name: '保存反馈并自动学习', exact: true }).click();
    await page.getByText('这份数据已经学习过，本次未重复增加样本。', { exact: true }).waitFor();
    check('feedback_deduplicates', true);
    await page.getByText('查看自动计算的指标与测试假设', { exact: true }).click();
    check('feedback_rate_computed', (await page.locator('pre').last().textContent()).includes('0.05'));
    await page.screenshot({ path: path.join(evidence, 'feedback-learning.png'), fullPage: true });
    await page.getByRole('button', { name: '停用此反馈', exact: true }).click();
    await page.getByText('反馈已停用，后续不再使用。', { exact: true }).waitFor();
    check('feedback_can_be_disabled', true);
    await page.getByRole('button', { name: '全库整理清单', exact: true }).click();
    await page.locator('.lx-k-table tbody tr').first().waitFor();
    check('full_inventory', (await page.locator('.lx-k-table tbody tr').count()) === 100);
    await page.getByRole('button', { name: '下一页', exact: true }).click();
    await page.getByText(/101—200/).waitFor();
    check('inventory_pagination', true);
    await page.getByRole('button', { name: '检索知识', exact: true }).click();
    await page.setViewportSize({ width: 900, height: 1000 });
    await page.screenshot({ path: path.join(evidence, 'knowledge-900.png'), fullPage: true });
    check('responsive_no_horizontal_overflow', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    check('no_page_errors', failures.length === 0);
    fs.writeFileSync(path.join(evidence, 'browser-result.json'), JSON.stringify({ passed: true, checks, failures, target }, null, 2));
    console.log(JSON.stringify({ passed: true, checks, failures, evidence }));
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
